import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceIndex = process.argv.indexOf("--source");
const source = sourceIndex >= 0 ? process.argv[sourceIndex + 1] : "";
const output = path.join(root, "src/domain/motionMatchingCatalog.generated.ts");

if (!source) {
  console.error("usage: node scripts/sync-motion-matching-catalog.mjs --source <overlay-fx-generator/SKILL.md>");
  process.exit(1);
}

const markdown = fs.readFileSync(path.resolve(source), "utf8");
const preferencesPath = path.join(path.dirname(path.resolve(source)), "我的偏好.default.md");
const preferences = fs.readFileSync(preferencesPath, "utf8");
const begin = markdown.indexOf("<!-- CARDS:AUTO-BEGIN");
const end = markdown.indexOf("<!-- CARDS:AUTO-END -->");
if (begin < 0 || end <= begin) throw new Error("参考 Skill 中没有找到卡片库标记");

const cards = [];
let purposeGroup = "";
for (const line of markdown.slice(begin, end).split("\n")) {
  const heading = /^###\s+(.+?)(?:\(|$)/.exec(line);
  if (heading) {
    purposeGroup = heading[1].trim();
    continue;
  }
  if (!line.startsWith("| `")) continue;
  const bars = [];
  for (let index = 0; index < line.length; index += 1) {
    if (line[index] === "|" && line[index - 1] !== "\\") bars.push(index);
  }
  if (bars.length < 6) continue;
  const cell = (from, to) => line.slice(bars[from] + 1, bars[to]).trim();
  const id = /^`([a-z0-9-]+)`/.exec(cell(0, 1))?.[1];
  if (!id || purposeGroup.startsWith("⚠")) continue;
  const verticalPolicy = cell(1, 2);
  const purpose = cell(2, 3);
  const triggerWhen = cell(3, 4);
  const parameterGuide = line.slice(bars[4] + 1, bars.at(-1)).trim();
  if (!triggerWhen || triggerWhen.includes("⬜ 待补")) throw new Error(`${id} 缺少触发条件`);
  cards.push({ id, purposeGroup, verticalPolicy, purpose, triggerWhen, parameterGuide });
}

if (!cards.length) throw new Error("没有从参考 Skill 解析到动效卡片");

function preferenceRow(label) {
  const line = preferences.split("\n").find((candidate) => candidate.startsWith(`| ${label} |`));
  const value = line?.match(/\*\*([^*]+)\*\*/u)?.[1];
  if (!value) throw new Error(`默认偏好缺少“${label}”`);
  return value;
}

function numberRange(value, label) {
  const match = /(\d+(?:\.\d+)?)\s*[-–]\s*(\d+(?:\.\d+)?)/u.exec(value);
  if (!match) throw new Error(`默认偏好“${label}”不是数值区间`);
  return { min: Number(match[1]), max: Number(match[2]) };
}

function firstNumber(value, label) {
  const match = /\d+(?:\.\d+)?/u.exec(value);
  if (!match) throw new Error(`默认偏好“${label}”缺少数值`);
  return Number(match[0]);
}

const segmentRange = numberRange(markdown.match(/\*\*段\s*=\s*([^*]+)\*\*/u)?.[1] ?? "", "典型段落时长");
const hookDeadline = firstNumber(markdown.match(/开头\s*0-(\d+(?:\.\d+)?)s/u)?.[1] ?? "", "开场钩子截止时间");
const policy = {
  densityPerMinute: numberRange(preferenceRow("密度区间"), "密度区间"),
  newActionIntervalSeconds: numberRange(preferenceRow("新动作间隔"), "新动作间隔"),
  typicalSegmentSeconds: segmentRange,
  openingHookDeadlineSeconds: hookDeadline,
  maxConcurrentContentLayers: firstNumber(preferenceRow("同屏叠卡上限"), "同屏叠卡上限"),
  minContentEntryStaggerSeconds: firstNumber(preferenceRow("同屏进场错开"), "同屏进场错开")
};

const contents = `// Generated by scripts/sync-motion-matching-catalog.mjs. Do not edit manually.\n` +
  `export const referenceMotionMatchingPolicy = ${JSON.stringify(policy, null, 2)} as const;\n\n` +
  `export const referenceMotionMatchingCards = ${JSON.stringify(cards, null, 2)} as const;\n`;
fs.writeFileSync(output, contents);
console.log(`已同步 ${cards.length} 张参考动效匹配卡`);
